#!/usr/bin/env python3

"""
Create Figure 5: Protein and functional context of candidate residues.

Panel A
-------
ST3GAL4 candidates resolved through seven-reference reconciliation.
Shows shared GT29/sialyltransferase family context and distinguishes
candidates with CDD cd23982 overlap across all seven references.

Panel B
-------
Four RefSeq-X2 CMAH candidates mapped to XP_024839792.1.
Shows broad CMAH-family PANTHER/InterPro context only.

Input tables are publication-facing frozen source data generated by:
    scripts/figures/generate_figure5_source_data.py
"""

import csv
from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.patches import Rectangle


# ---------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------

ROOT = Path(__file__).resolve().parents[2]

SOURCE_DIR = ROOT / "results/figures/source_data"

ST3_FILE = SOURCE_DIR / "Figure5_panelA_ST3GAL4_context.tsv"
CMAH_FILE = SOURCE_DIR / "Figure5_panelB_CMAH_X2_context.tsv"

OUT_PNG = ROOT / "results/figures/Figure5_protein_functional_context.png"
OUT_SVG = ROOT / "results/figures/Figure5_protein_functional_context.svg"


# ---------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------

def read_tsv(path):
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def add_candidate(
    ax,
    x,
    label,
    y_base,
    y_label,
    marker="o",
    label_x=None,
):
    """
    Draw one candidate at its true residue coordinate.

    The marker remains fixed at x.
    label_x can be displaced horizontally to prevent collisions.
    The leader line therefore always links the displayed label
    back to the true residue position.
    """

    if label_x is None:
        label_x = x

    ax.plot(
        [x, label_x],
        [y_base, y_label - 0.035],
        linewidth=1.1,
        zorder=3,
    )

    ax.scatter(
        [x],
        [y_base],
        marker=marker,
        s=55,
        zorder=4,
    )

    ax.text(
        label_x,
        y_label,
        label,
        ha="center",
        va="bottom",
        fontsize=9,
        rotation=0,
    )


# ---------------------------------------------------------------------
# Load source data
# ---------------------------------------------------------------------

st3 = read_tsv(ST3_FILE)
cmah = read_tsv(CMAH_FILE)


# ---------------------------------------------------------------------
# Validate source data
# ---------------------------------------------------------------------

assert len(st3) == 5, (
    f"Expected 5 ST3GAL4 candidates; found {len(st3)}"
)

assert len(cmah) == 4, (
    f"Expected 4 CMAH candidates; found {len(cmah)}"
)

st3.sort(key=lambda r: int(r["Protein_position"]))
cmah.sort(key=lambda r: int(r["Protein_position"]))

assert [r["Protein_change"] for r in st3] == [
    "Y190S",
    "R203S",
    "Y320F",
    "I333M",
    "H334Q",
]

assert [r["Protein_change"] for r in cmah] == [
    "N386S",
    "I388M",
    "P424L",
    "F512Y",
]

assert all(
    r["References_reconciled"] == "7"
    for r in st3
)

assert [
    r["Protein_change"]
    for r in st3
    if r["cd23982_all_seven_overlap"] == "YES"
] == [
    "R203S",
    "Y320F",
    "I333M",
    "H334Q",
]

assert [
    r["Protein_change"]
    for r in st3
    if r["cd23982_all_seven_overlap"] == "NO"
] == [
    "Y190S",
]

assert all(
    r["Reference_protein"] == "XP_024839792.1"
    for r in cmah
)

assert all(
    r["Signature_accession"] == "PTHR46522"
    for r in cmah
)

assert all(
    r["InterPro_entry"] == "IPR027033"
    for r in cmah
)

assert all(
    r["Family_interval_start"] == "5"
    for r in cmah
)

assert all(
    r["Family_interval_end"] == "576"
    for r in cmah
)

assert all(
    r["Context_interpretation"] == "BROAD_FAMILY_OVERLAP_ONLY"
    for r in cmah
)


# ---------------------------------------------------------------------
# Figure layout
# ---------------------------------------------------------------------

fig = plt.figure(figsize=(11.5, 7.2))

gs = fig.add_gridspec(
    2,
    1,
    height_ratios=[1, 1],
    hspace=0.55,
)

ax_a = fig.add_subplot(gs[0, 0])
ax_b = fig.add_subplot(gs[1, 0])


# =====================================================================
# Panel A: ST3GAL4 multi-reference reconciliation
# =====================================================================

ax_a.set_title(
    "A   ST3GAL4 multi-reference reconciled context",
    loc="left",
    fontsize=12,
    fontweight="bold",
    pad=12,
)

# Display window selected only to encompass the five reconciled
# candidate positions. This is not intended to imply full protein
# or exact domain boundaries.
xmin_a = 160
xmax_a = 360

y_family = 0.48
family_height = 0.18

ax_a.add_patch(
    Rectangle(
        (
            xmin_a,
            y_family - family_height / 2,
        ),
        xmax_a - xmin_a,
        family_height,
        alpha=0.22,
        linewidth=1.0,
        zorder=1,
    )
)

ax_a.text(
    (xmin_a + xmax_a) / 2,
    y_family,
    "Shared GT29 / sialyltransferase family context\n"
    "(PF00777; IPR001675, IPR038578, IPR051142)",
    ha="center",
    va="center",
    fontsize=9,
)

candidate_base_a = y_family + family_height / 2

# Explicit label positions prevent ambiguity among the tightly spaced
# Y320F, I333M and H334Q candidates.
st3_layout = {
    "Y190S": {
        "label_x": 190,
        "y_label": 0.82,
    },
    "R203S": {
        "label_x": 203,
        "y_label": 0.90,
    },
    "Y320F": {
        "label_x": 316,
        "y_label": 0.84,
    },
    "I333M": {
        "label_x": 329,
        "y_label": 1.03,
    },
    "H334Q": {
        "label_x": 342,
        "y_label": 0.85,
    },
}

for row in st3:

    pos = int(row["Protein_position"])
    label = row["Protein_change"]

    marker = (
        "s"
        if row["cd23982_all_seven_overlap"] == "YES"
        else "o"
    )

    layout = st3_layout[label]

    add_candidate(
        ax=ax_a,
        x=pos,
        label=label,
        y_base=candidate_base_a,
        y_label=layout["y_label"],
        marker=marker,
        label_x=layout["label_x"],
    )


ax_a.text(
    xmin_a,
    0.13,
    "5 candidates reconciled across 7 bovine protein representations",
    ha="left",
    va="center",
    fontsize=9,
)

ax_a.text(
    xmin_a,
    0.04,
    "R203S, Y320F, I333M and H334Q also overlap CDD cd23982 "
    "across all 7 representations",
    ha="left",
    va="center",
    fontsize=9,
)

ax_a.set_xlim(
    xmin_a,
    xmax_a,
)

ax_a.set_ylim(
    -0.03,
    1.12,
)

ax_a.set_xlabel(
    "Protein residue position"
)

ax_a.set_yticks([])

for spine in [
    "left",
    "right",
    "top",
]:
    ax_a.spines[spine].set_visible(False)


legend_a = [
    Line2D(
        [0],
        [0],
        marker="s",
        linestyle="None",
        markersize=7,
        label="cd23982 overlap across all 7 references",
    ),
    Line2D(
        [0],
        [0],
        marker="o",
        linestyle="None",
        markersize=7,
        label="No cd23982 all-seven overlap",
    ),
]

ax_a.legend(
    handles=legend_a,
    frameon=False,
    fontsize=8.5,
    loc="upper left",
    bbox_to_anchor=(0.0, -0.20),
    ncol=2,
)


# =====================================================================
# Panel B: CMAH RefSeq-X2 sequence-based context
# =====================================================================

ax_b.set_title(
    "B   CMAH RefSeq-X2 sequence-based context",
    loc="left",
    fontsize=12,
    fontweight="bold",
    pad=12,
)

protein_start = 1
protein_end = 576

family_start = int(
    cmah[0]["Family_interval_start"]
)

family_end = int(
    cmah[0]["Family_interval_end"]
)

y_protein = 0.48
protein_height = 0.18


# Protein backbone
ax_b.plot(
    [protein_start, protein_end],
    [y_protein, y_protein],
    linewidth=2.0,
    zorder=1,
)


# Broad CMAH family context only.
ax_b.add_patch(
    Rectangle(
        (
            family_start,
            y_protein - protein_height / 2,
        ),
        family_end - family_start,
        protein_height,
        alpha=0.22,
        linewidth=1.0,
        zorder=2,
    )
)

ax_b.text(
    (family_start + family_end) / 2,
    y_protein,
    "Broad CMAH-family context\n"
    "PTHR46522 / IPR027033 (residues 5–576)",
    ha="center",
    va="center",
    fontsize=9,
)

candidate_base_b = y_protein + protein_height / 2

# N386S and I388M are only two residues apart.
# Their labels are deliberately displaced in opposite directions,
# while markers remain at the true residue coordinates.
cmah_layout = {
    "N386S": {
        "label_x": 362,
        "y_label": 0.82,
    },
    "I388M": {
        "label_x": 398,
        "y_label": 0.99,
    },
    "P424L": {
        "label_x": 424,
        "y_label": 0.84,
    },
    "F512Y": {
        "label_x": 512,
        "y_label": 0.90,
    },
}

for row in cmah:

    pos = int(row["Protein_position"])
    label = row["Protein_change"]

    layout = cmah_layout[label]

    add_candidate(
        ax=ax_b,
        x=pos,
        label=label,
        y_base=candidate_base_b,
        y_label=layout["y_label"],
        marker="o",
        label_x=layout["label_x"],
    )


ax_b.text(
    protein_start,
    0.13,
    "Reference protein: XP_024839792.1 | InterProScan 5.78-109.0",
    ha="left",
    va="center",
    fontsize=9,
)

ax_b.text(
    protein_start,
    0.04,
    "All 4 candidates: broad family-level overlap only; "
    "no narrower non-PANTHER signature at the candidate residue",
    ha="left",
    va="center",
    fontsize=9,
)

ax_b.set_xlim(
    0,
    590,
)

ax_b.set_ylim(
    -0.03,
    1.12,
)

ax_b.set_xlabel(
    "Protein residue position"
)

ax_b.set_yticks([])

for spine in [
    "left",
    "right",
    "top",
]:
    ax_b.spines[spine].set_visible(False)


# ---------------------------------------------------------------------
# Export
# ---------------------------------------------------------------------

fig.subplots_adjust(
    left=0.08,
    right=0.98,
    top=0.95,
    bottom=0.12,
)

OUT_PNG.parent.mkdir(
    parents=True,
    exist_ok=True,
)

fig.savefig(
    OUT_PNG,
    dpi=600,
    bbox_inches="tight",
)

fig.savefig(
    OUT_SVG,
    bbox_inches="tight",
)

plt.close(fig)


# ---------------------------------------------------------------------
# Completion message
# ---------------------------------------------------------------------

print("Figure 5 generated successfully.")
print(f"  {OUT_PNG.relative_to(ROOT)}")
print(f"  {OUT_SVG.relative_to(ROOT)}")
